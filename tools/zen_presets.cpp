// The preset converter: Zenthesizer's factory presets (Presets.h, PresetsMore.h) as Zen-Lite knob positions.
// Each starts from the plugin's defaults and the plate kit, as the plugin does, and is then mapped knob by knob the
// way the firmware reads its knobs (k x 1024 / 127). What the FM-1 version doesn't have is left out:
//   B UNISON, AIR (breath noise) and the arpeggiator; slots aimed at B UNISON or AIR are dropped;
//   presets built on the plucked STRING oscillator are skipped (there is no string model here);
//   a synced delay becomes the same time at 90 BPM (the plugin's tempo with no host: its drum clock's default).
// Run by tools/make_presets.sh, which writes firmware/gen/zen_presets.h.
#include "Presets.h"
#include "zen_params.h"
#include <cmath>
#include <cstdio>
#include <map>
#include <string>

static int knob (float v) { return (int) std::lround (std::min (1.0f, std::max (0.0f, v)) * 127.0f); }
static int bip (float v)  { return std::min (127, std::max (0, 64 + (int) std::lround ((v - 0.5f) * 2.0f * 63.0f))); }

int main()
{
    const auto& all = presets::all();
    std::printf ("/* SPDX-License-Identifier: GPL-3.0-only */\n"
                 "/* Generated by tools/make_presets.sh from Zenthesizer's factory presets. Do not edit. */\n"
                 "#ifndef ZEN_PRESETS_H\n#define ZEN_PRESETS_H\n#include \"zen_params.h\"\n");
    std::string body;
    int count = 0, skipped = 0;
    char line[2048];
    auto emit = [&] (const std::string& name, const std::string& cat, const int* p, const zps_t* s) {
        std::string t = "  {\"" + name + "\", \"" + cat + "\", {";
        for (int i = 0; i < P_N; ++i) t += std::to_string (p[i]) + (i + 1 < P_N ? "," : "");
        t += "}, {";
        for (int i = 0; i < ZM_NSLOTS; ++i)
        {
            std::snprintf (line, sizeof line, "{%d,%d,%d}%s", s[i].src, s[i].dst, s[i].amt, i + 1 < ZM_NSLOTS ? "," : "");
            t += line;
        }
        body += t + "}},\n";
        ++count;
    };

    // 0: Zen-Lite's own starting sound
    {
        int p[P_N]; zps_t s[ZM_NSLOTS] {};
        for (int i = 0; i < P_N; ++i) p[i] = PARAM[i].def;
        for (int i = 0; i < 7; ++i) s[i] = ZKIT[i];
        emit ("Zen-Lite", "Zen-Lite", p, s);
    }
    for (const auto& pr : all)
    {
        zen::Settings d;                                       // the plugin's defaults
        std::map<std::string, float> v = {
            {"aWave", (float) d.aWave}, {"aTune", d.aTune}, {"aDetune", d.aDetune}, {"aShape", d.aShape}, {"aLevel", d.aLevel},
            {"bTable", (float) d.bTable}, {"bPos", d.bPos}, {"bWarp", d.bWarp}, {"bLevel", d.bLevel},
            {"cutoff", d.cutoff}, {"res", d.res}, {"drive", d.drive}, {"envAmt", d.envAmt}, {"keyTrack", d.keyTrack},
            {"ampA", d.ampA}, {"ampD", d.ampD}, {"ampS", d.ampS}, {"ampR", d.ampR},
            {"e1A", d.e1A}, {"e1D", d.e1D}, {"e1S", d.e1S}, {"e1R", d.e1R}, {"e2A", d.e2A}, {"e2D", d.e2D}, {"e2S", d.e2S}, {"e2R", d.e2R},
            {"lfo1Rate", d.lfo1Rate}, {"lfo1Shape", (float) d.lfo1Shape}, {"lfo2Rate", d.lfo2Rate}, {"lfo2Shape", (float) d.lfo2Shape},
            {"randRate", d.randRate}, {"randSmooth", d.randSmooth},
            {"glide", d.glide}, {"spread", d.spread}, {"volume", d.volume}, {"velSens", d.velSens},
            {"chorusMix", d.chorusMix}, {"chorusDepth", d.chorusDepth},
            {"delayTime", d.delayTime}, {"delaySync", (float) d.delaySync}, {"delayFeedback", d.delayFeedback},
            {"delayTone", d.delayTone}, {"delayMix", d.delayMix},
            {"reverbSize", d.reverbSize}, {"reverbDecay", d.reverbDecay}, {"reverbDamp", d.reverbDamp},
            {"reverbShimmer", d.reverbShimmer}, {"reverbMix", d.reverbMix} };
        for (const auto& e : pr.values) v[e.id] = e.v;          // (ids it has no knob for are ignored)
        if ((int) v["aWave"] == 4) { ++skipped; std::fprintf (stderr, "skipped (STRING): %s\n", pr.name); continue; }

        int p[P_N];
        for (int i = 0; i < P_N; ++i) p[i] = PARAM[i].def;
        p[P_CUT] = knob (v["cutoff"]); p[P_RES] = knob (v["res"]); p[P_DRIVE] = knob (v["drive"]); p[P_ENVAMT] = bip (v["envAmt"]);
        p[P_WAVE] = std::min (3, std::max (0, (int) v["aWave"])); p[P_SHAPE] = knob (v["aShape"]);
        p[P_DET] = knob (v["aDetune"]); p[P_ALEV] = knob (v["aLevel"]);
        p[P_TABLE] = std::min (3, std::max (0, (int) v["bTable"])); p[P_POS] = knob (v["bPos"]);
        p[P_WARP] = knob (v["bWarp"]); p[P_BLEV] = knob (v["bLevel"]);
        p[P_TUNE] = std::min (48, std::max (0, 24 + (int) zen::tuneSemisSnapped (v["aTune"])));
        p[P_GLIDE] = knob (v["glide"]); p[P_VELS] = knob (v["velSens"]); p[P_VOL] = knob (v["volume"]);
        p[P_ATT] = knob (v["ampA"]); p[P_DEC] = knob (v["ampD"]); p[P_SUS] = knob (v["ampS"]); p[P_REL] = knob (v["ampR"]);
        p[P_E1A] = knob (v["e1A"]); p[P_E1D] = knob (v["e1D"]); p[P_E1S] = knob (v["e1S"]); p[P_E1R] = knob (v["e1R"]);
        p[P_E2A] = knob (v["e2A"]); p[P_E2D] = knob (v["e2D"]); p[P_E2S] = knob (v["e2S"]); p[P_E2R] = knob (v["e2R"]);
        p[P_L1RATE] = knob (v["lfo1Rate"]); p[P_L1SHAPE] = std::min (4, (int) v["lfo1Shape"]);
        p[P_L2RATE] = knob (v["lfo2Rate"]); p[P_L2SHAPE] = std::min (4, (int) v["lfo2Shape"]);
        p[P_RRATE] = knob (v["randRate"]); p[P_RSMOOTH] = knob (v["randSmooth"]);
        p[P_KTRACK] = knob (v["keyTrack"]); p[P_WIDTH] = knob (v["spread"]);
        p[P_CHORUS] = knob (v["chorusMix"]); p[P_DEPTH] = knob (v["chorusDepth"]);
        p[P_REVERB] = knob (v["reverbMix"]); p[P_RDECAY] = knob (v["reverbDecay"]); p[P_SHIMMER] = knob (v["reverbShimmer"]);
        p[P_SIZE] = knob (v["reverbSize"]); p[P_DAMP] = knob (v["reverbDamp"]);
        float dt = v["delayTime"];
        if (const float beats = zen::delaySyncBeats ((int) v["delaySync"]); beats > 0.0f)
            dt = std::log (beats * 60.0f / 90.0f * 1000.0f / 40.0f) / std::log (37.5f);
        p[P_DTIME] = knob (dt); p[P_DFB] = knob (v["delayFeedback"]); p[P_DTONE] = knob (v["delayTone"]);
        p[P_DELAY] = knob (v["delayMix"]);

        zps_t s[ZM_NSLOTS] {};
        for (int i = 0; i < 7; ++i) s[i] = ZKIT[i];
        int n = 7;
        for (const auto& sl : pr.slots)
        {
            if (sl.d == zen::Dst::bUnison || sl.d == zen::Dst::air) continue;
            if (n == ZM_NSLOTS) { std::fprintf (stderr, "too many slots: %s\n", pr.name); break; }
            s[n].src = (uint8_t) sl.s; s[n].dst = (uint8_t) sl.d;
            s[n].amt = (int16_t) std::lround (std::min (1.0f, std::max (-1.0f, sl.amt)) * 1024.0f);
            ++n;
        }
        auto clean = [] (const char* c) { std::string o; for (; *c; ++c) o += (*c == '"' || *c == '\\') ? ' ' : *c; return o; };
        emit (clean (pr.name), clean (pr.category), p, s);
    }
    std::printf ("#define ZPRESETS %d\nstatic const zpreset_t ZPRESET[ZPRESETS] = {\n%s};\n#endif\n", count, body.c_str());
    std::fprintf (stderr, "%d presets (%d skipped)\n", count, skipped);
    return 0;
}
